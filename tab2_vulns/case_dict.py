def normalize_first_word(description: str) -> str:
    if not description:
        return description

    words = description.split(maxsplit=1)
    if not words:
        return description

    first = words[0]
    replacement = CASE_DICT.get(first.lower())
    if replacement is None:
        return description

    tail = words[1] if len(words) > 1 else ""
    return (replacement + " " + tail).strip()